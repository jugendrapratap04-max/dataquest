/* Deep-learning practice problems.
 *
 * Its own module, registered in apply-problems.mjs, for the reason spelled out
 * at the top of ml-problems.mjs: `db:content` only UPDATES seed problems that
 * already exist and never creates them, while the modules in SETS upsert.
 *
 * Everything here is deliberately numpy-free and framework-free. Not because
 * scikit-learn is unavailable — the lessons use it heavily — but because these
 * problems are the mechanisms rather than the API: a neuron is a weighted sum
 * and a max, a convolution is two nested loops, bag of words is `.count()`. A
 * student who has written those cannot be mystified by the library later, and a
 * student who has only called MLPClassifier can be.
 */

